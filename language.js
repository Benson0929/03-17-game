function translateLine(text) {
  return gameLanguage === "zh-Hant" ? (traditionalChinese[text] ?? text) : text;
}
function localizeStory(text) {
  return text.split("\n").map(function (line) {
    // Preserve all timing, image, and sound commands in their original order.
    return line.split(/(\[[A-Z_]+(?:=[^\]]+)?\])/g).map(function (part) {
      if (part.startsWith("[")) return part;
      return part.replace(/^(\s*)(.*?)(\s*)$/, function (_, before, words, after) {
        return before + translateLine(words) + after;
      });
    }).join("");
  }).join("\n");
}
function localizeButtons(html) {
  const template = document.createElement("template");
  template.innerHTML = html;
  template.content.querySelectorAll("button").forEach(function (button) {
    button.textContent = translateLine(button.textContent.trim());
  });
  return template.innerHTML;
}
